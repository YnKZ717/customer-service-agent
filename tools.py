def search_knowledge_base(query: str) -> tuple[str, str]:
    """搜索知识库，返回 (分类名, 答案)"""
    for category, data in KNOWLEDGE_BASE.items():
        for keyword in data["keywords"]:
            if keyword in query:
                return category, data["answer"]
    return None, '抱歉，暂未找到相关信息。请问还有其他问题吗？或输入"人工"转接人工客服。'


def transfer_to_human(user_input: str, history: list) -> dict:
    """转接人工客服，生成工单信息"""
    ticket_id = f"TK-{hash(user_input) % 10000:04d}"
    summary = user_input[:50]  # 截取前50字作为摘要
    return {
        "response": f"已为您转接人工客服，工单号：{ticket_id}。客服将尽快与您联系。",
        "ticket_id": ticket_id,
        "ticket_summary": summary,
    }


